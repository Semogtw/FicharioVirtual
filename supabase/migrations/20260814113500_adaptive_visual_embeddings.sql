create or replace function public.search_pages_visual_semantic(
  query_embedding text,
  target_model text,
  notebook_filter uuid default null,
  result_limit integer default 12
)
returns table (
  page_id uuid,
  document_id uuid,
  document_title text,
  notebook_id uuid,
  notebook_name text,
  page_number integer,
  visual_similarity double precision
)
language plpgsql
stable
security invoker
set search_path = ''
as $$
begin
  if (select auth.uid()) is null or not (select public.is_authorized_user()) then
    raise exception using errcode = '42501', message = 'Not authorized';
  end if;
  if target_model !~ '^[A-Za-z0-9._-]{3,128}$'
    or query_embedding is null
    or char_length(query_embedding) > 24000
    or result_limit is null
    or result_limit < 1
    or result_limit > 50 then
    raise exception using errcode = '22023', message = 'Invalid visual semantic search';
  end if;

  perform set_config('hnsw.ef_search', '80', true);

  return query
  with query_vector as (
    select query_embedding::extensions.vector(768) as value
  )
  select
    e.page_id,
    d.id,
    d.title,
    n.id,
    n.name,
    p.page_number,
    greatest(
      0.0,
      least(1.0, 1.0 - (e.embedding OPERATOR(extensions.<=>) q.value))
    )::double precision
  from public.page_visual_embeddings e
  join public.pages p
    on p.id = e.page_id
   and p.user_id = e.user_id
  join public.documents d
    on d.id = p.document_id
   and d.user_id = p.user_id
  left join public.notebooks n
    on n.id = d.notebook_id
   and n.user_id = d.user_id
  cross join query_vector q
  where e.user_id = (select auth.uid())
    and e.model = target_model
    and (notebook_filter is null or d.notebook_id = notebook_filter)
  order by e.embedding OPERATOR(extensions.<=>) q.value asc, d.title asc, p.page_number asc
  limit result_limit;
end;
$$;

create or replace function public.visual_embedding_stats(
  target_model text
)
returns table (
  indexed_pages bigint,
  pending_jobs bigint,
  failed_jobs bigint,
  latest_event_at timestamptz
)
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  if (select auth.uid()) is null or not (select public.is_authorized_user()) then
    raise exception using errcode = '42501', message = 'Not authorized';
  end if;
  if target_model !~ '^[A-Za-z0-9._-]{3,128}$' then
    raise exception using errcode = '22023', message = 'Invalid visual embedding model';
  end if;

  return query
  select
    (select count(*) from public.page_visual_embeddings e
      where e.user_id = (select auth.uid()) and e.model = target_model)::bigint,
    (select count(*) from public.page_visual_embedding_jobs j
      where j.user_id = (select auth.uid())
        and j.model = target_model
        and j.status in ('queued', 'processing', 'retryable', 'blocked_quota'))::bigint,
    (select count(*) from public.page_visual_embedding_jobs j
      where j.user_id = (select auth.uid())
        and j.model = target_model
        and j.status = 'failed')::bigint,
    (select max(e.created_at) from public.semantic_visual_events e
      where e.user_id = (select auth.uid()) and e.model = target_model);
end;
$$;

