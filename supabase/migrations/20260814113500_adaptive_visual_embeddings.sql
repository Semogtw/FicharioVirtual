create or replace function public.claim_page_visual_embedding_jobs(
  target_model text,
  result_limit integer default 4
)
returns table (
  job_id uuid,
  user_id uuid,
  page_id uuid,
  document_id uuid,
  document_kind text,
  media_path text,
  mime_type text,
  routing_version text,
  routing_reason text,
  attempt_count integer,
  temporary_media boolean
)
language plpgsql
security definer
set search_path = ''
as $$
begin
  if target_model !~ '^[A-Za-z0-9._-]{3,128}$'
    or result_limit is null
    or result_limit < 1
    or result_limit > 6 then
    raise exception using errcode = '22023', message = 'Invalid visual worker claim';
  end if;

  return query
  with candidates as (
    select j.id
    from public.page_visual_embedding_jobs j
    join public.app_users a
      on a.user_id = j.user_id
     and a.is_active = true
    where j.model = target_model
      and (
        j.status in ('queued', 'retryable', 'blocked_quota')
        or (j.status = 'processing' and j.claimed_at < now() - interval '5 minutes')
      )
      and (j.retry_after is null or j.retry_after <= now())
    order by coalesce(j.retry_after, j.created_at), j.created_at, j.id
    for update of j skip locked
    limit result_limit
  ), claimed as (
    update public.page_visual_embedding_jobs j
    set status = 'processing',
        attempt_count = least(j.attempt_count + 1, 100),
        claimed_at = now(),
        updated_at = now(),
        safe_error_code = null
    from candidates c
    where j.id = c.id
    returning j.*
  )
  select
    c.id,
    c.user_id,
    c.page_id,
    c.document_id,
    c.document_kind,
    c.media_path,
    c.mime_type,
    c.routing_version,
    c.routing_reason,
    c.attempt_count,
    c.temporary_media
  from claimed c
  order by c.claimed_at, c.id;
end;
$$;

create or replace function public.reuse_page_visual_embedding_job(
  target_job_id uuid,
  target_source_hash text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  job public.page_visual_embedding_jobs%rowtype;
  matched boolean;
begin
  if target_job_id is null or target_source_hash !~ '^[0-9a-f]{64}$' then
    raise exception using errcode = '22023', message = 'Invalid visual reuse request';
  end if;

  select * into job
  from public.page_visual_embedding_jobs
  where id = target_job_id
  for update;

  if not found or job.status <> 'processing' then
    return jsonb_build_object('reused', false);
  end if;

  select exists (
    select 1
    from public.page_visual_embeddings e
    where e.user_id = job.user_id
      and e.page_id = job.page_id
      and e.model = job.model
      and e.source_hash = target_source_hash
  ) into matched;

  if not matched then
    return jsonb_build_object('reused', false);
  end if;

  update public.page_visual_embedding_jobs
  set status = 'ready',
      retry_after = null,
      safe_error_code = null,
      updated_at = now()
  where id = job.id;

  return jsonb_build_object(
    'reused', true,
    'terminal', true,
    'pageId', job.page_id,
    'userId', job.user_id,
    'mediaPath', job.media_path,
    'temporaryMedia', job.temporary_media
  );
end;
$$;

create or replace function public.complete_page_visual_embedding_job(
  target_job_id uuid,
  target_source_hash text,
  embedding_text text,
  target_bytes_total bigint
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  job public.page_visual_embedding_jobs%rowtype;
  current_media_path text;
  current_document_path text;
  current_document_kind text;
  media_is_current boolean := false;
begin
  if target_job_id is null
    or target_source_hash !~ '^[0-9a-f]{64}$'
    or embedding_text is null
    or char_length(embedding_text) > 24000
    or target_bytes_total is null
    or target_bytes_total < 1
    or target_bytes_total > 25165824 then
    raise exception using errcode = '22023', message = 'Invalid visual embedding completion';
  end if;

  select * into job
  from public.page_visual_embedding_jobs
  where id = target_job_id
  for update;

  if not found or job.status <> 'processing' then
    return jsonb_build_object('stored', false, 'code', 'job_not_processing');
  end if;

  select p.temporary_image_path, d.storage_path, d.kind::text
    into current_media_path, current_document_path, current_document_kind
  from public.pages p
  join public.documents d
    on d.id = p.document_id
   and d.user_id = p.user_id
  where p.id = job.page_id
    and p.user_id = job.user_id
    and p.document_id = job.document_id;

  media_is_current :=
    (job.temporary_media and current_media_path = job.media_path)
    or (
      not job.temporary_media
      and current_document_kind = 'image'
      and current_document_path = job.media_path
    );

  if not coalesce(media_is_current, false) then
    update public.page_visual_embedding_jobs
    set status = 'failed',
        safe_error_code = 'visual_source_stale',
        retry_after = null,
        updated_at = now()
    where id = job.id;
    return jsonb_build_object(
      'stored', false,
      'terminal', true,
      'code', 'visual_source_stale',
      'pageId', job.page_id,
      'userId', job.user_id,
      'mediaPath', job.media_path,
      'temporaryMedia', job.temporary_media
    );
  end if;

  insert into public.page_visual_embeddings (
    user_id,
    page_id,
    model,
    source_hash,
    routing_version,
    routing_reason,
    embedding,
    updated_at
  ) values (
    job.user_id,
    job.page_id,
    job.model,
    target_source_hash,
    job.routing_version,
    job.routing_reason,
    embedding_text::extensions.vector(768),
    now()
  )
  on conflict (user_id, page_id, model)
  do update set
    source_hash = excluded.source_hash,
    routing_version = excluded.routing_version,
    routing_reason = excluded.routing_reason,
    embedding = excluded.embedding,
    updated_at = now();

  update public.page_visual_embedding_jobs
  set status = 'ready',
      retry_after = null,
      safe_error_code = null,
      updated_at = now()
  where id = job.id;

  return jsonb_build_object(
    'stored', true,
    'terminal', true,
    'pageId', job.page_id,
    'userId', job.user_id,
    'mediaPath', job.media_path,
    'temporaryMedia', job.temporary_media
  );
end;
$$;

create or replace function public.finish_page_visual_embedding_job(
  target_job_id uuid,
  terminal_status text,
  safe_error_code text,
  retry_at timestamptz
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  job public.page_visual_embedding_jobs%rowtype;
  is_terminal boolean;
  requested_error_code text := safe_error_code;
begin
  if target_job_id is null
    or terminal_status not in ('retryable', 'blocked_quota', 'failed')
    or safe_error_code !~ '^[a-z][a-z0-9_]{1,95}$'
    or (terminal_status = 'failed' and retry_at is not null)
    or (terminal_status <> 'failed' and retry_at is null) then
    raise exception using errcode = '22023', message = 'Invalid visual job failure';
  end if;

  select * into job
  from public.page_visual_embedding_jobs
  where id = target_job_id
  for update;

  if not found then
    return jsonb_build_object('updated', false);
  end if;

  is_terminal := terminal_status = 'failed';
  update public.page_visual_embedding_jobs
  set status = terminal_status,
      safe_error_code = requested_error_code,
      retry_after = retry_at,
      updated_at = now()
  where id = job.id;

  return jsonb_build_object(
    'updated', true,
    'terminal', is_terminal,
    'pageId', job.page_id,
    'userId', job.user_id,
    'mediaPath', job.media_path,
    'temporaryMedia', job.temporary_media
  );
end;
$$;

