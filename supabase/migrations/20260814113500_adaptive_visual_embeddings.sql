-- Adaptive page-level visual semantic enrichment.
-- Keeps visual vectors, operational queue state and telemetry separate from the
-- textual semantic index. All worker operations are service-role only.

create table public.page_visual_embeddings (
  id uuid primary key default extensions.gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  page_id uuid not null,
  model text not null check (model ~ '^[A-Za-z0-9._-]{3,128}$'),
  source_hash text not null check (source_hash ~ '^[0-9a-f]{64}$'),
  routing_version text not null check (routing_version ~ '^[a-z][a-z0-9._-]{2,63}$'),
  routing_reason text not null check (routing_reason ~ '^[a-z][a-z0-9_]{1,63}$'),
  embedding extensions.vector(768) not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, page_id, model),
  foreign key (page_id, user_id)
    references public.pages(id, user_id)
    on delete cascade
);

alter table public.page_visual_embeddings enable row level security;
alter table public.page_visual_embeddings force row level security;

create policy "Users can read their visual page embeddings"
  on public.page_visual_embeddings
  for select
  to authenticated
  using (
    user_id = (select auth.uid())
    and (select public.is_authorized_user())
  );

revoke all on table public.page_visual_embeddings from public, anon, authenticated;
grant select on table public.page_visual_embeddings to authenticated;
grant all on table public.page_visual_embeddings to service_role;

create index page_visual_embeddings_hnsw_idx
  on public.page_visual_embeddings
  using hnsw (embedding extensions.vector_cosine_ops);
create index page_visual_embeddings_owner_model_idx
  on public.page_visual_embeddings (user_id, model, updated_at desc);

create table public.page_visual_embedding_jobs (
  id uuid primary key default extensions.gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  page_id uuid not null,
  document_id uuid not null,
  model text not null check (model ~ '^[A-Za-z0-9._-]{3,128}$'),
  document_kind text not null check (document_kind in ('image', 'pdf')),
  media_path text not null check (char_length(media_path) between 3 and 1024),
  mime_type text not null check (mime_type in ('image/jpeg', 'image/png')),
  routing_version text not null check (routing_version ~ '^[a-z][a-z0-9._-]{2,63}$'),
  routing_reason text not null check (routing_reason ~ '^[a-z][a-z0-9_]{1,63}$'),
  temporary_media boolean not null default false,
  status text not null default 'queued' check (
    status in ('queued', 'processing', 'retryable', 'blocked_quota', 'ready', 'failed')
  ),
  attempt_count integer not null default 0 check (attempt_count between 0 and 100),
  retry_after timestamptz,
  safe_error_code text check (
    safe_error_code is null or safe_error_code ~ '^[a-z][a-z0-9_]{1,95}$'
  ),
  claimed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, page_id, model),
  foreign key (page_id, user_id)
    references public.pages(id, user_id)
    on delete cascade,
  foreign key (document_id, user_id)
    references public.documents(id, user_id)
    on delete cascade
);

alter table public.page_visual_embedding_jobs enable row level security;
alter table public.page_visual_embedding_jobs force row level security;
revoke all on table public.page_visual_embedding_jobs from public, anon, authenticated;
