create or replace function public.queue_page_visual_embedding_job_as_user(
  target_user_id uuid,
  target_page_id uuid,
  target_model text,
  target_media_path text,
  target_mime_type text,
  target_routing_reason text,
  target_routing_version text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  page_row record;
  allowed_path text;
  is_temporary boolean;
  queued_id uuid;
begin
  if target_user_id is null
    or target_page_id is null
    or target_model !~ '^[A-Za-z0-9._-]{3,128}$'
    or target_media_path is null
    or char_length(target_media_path) not between 3 and 1024
    or target_mime_type not in ('image/jpeg', 'image/png')
    or target_routing_reason !~ '^[a-z][a-z0-9_]{1,63}$'
    or target_routing_version !~ '^[a-z][a-z0-9._-]{2,63}$'
  then
    raise exception using errcode = '22023', message = 'Invalid visual embedding job';
  end if;

  select
    p.id as page_id,
    p.user_id,
    p.document_id,
    p.status::text as page_status,
    p.temporary_image_path,
    d.kind::text as document_kind,
    d.storage_path
  into page_row
  from public.pages p
  join public.documents d
    on d.id = p.document_id
   and d.user_id = p.user_id
  where p.id = target_page_id
    and p.user_id = target_user_id
  for update of p;

  if not found then
    raise exception using errcode = 'P0002', message = 'Page not found';
  end if;
  if page_row.page_status not in ('ready', 'needs_review') then
    return jsonb_build_object('queued', false, 'code', 'page_not_ready');
  end if;

  if page_row.temporary_image_path is not null
     and page_row.temporary_image_path = target_media_path then
    allowed_path := page_row.temporary_image_path;
    is_temporary := true;
  elsif page_row.document_kind = 'image'
     and page_row.storage_path = target_media_path then
    allowed_path := page_row.storage_path;
    is_temporary := false;
  else
    raise exception using errcode = '22023', message = 'Visual media path is not current';
  end if;

  insert into public.page_visual_embedding_jobs (
    user_id,
    page_id,
    document_id,
    model,
    document_kind,
    media_path,
    mime_type,
    routing_version,
    routing_reason,
    temporary_media,
    status,
    attempt_count,
    retry_after,
    safe_error_code,
    claimed_at,
    updated_at
  ) values (
    target_user_id,
    page_row.page_id,
    page_row.document_id,
    target_model,
    page_row.document_kind,
    allowed_path,
    target_mime_type,
    target_routing_version,
    target_routing_reason,
    is_temporary,
    'queued',
    0,
    null,
    null,
    null,
    now()
  )
  on conflict (user_id, page_id, model)
  do update set
    document_id = excluded.document_id,
    document_kind = excluded.document_kind,
    media_path = excluded.media_path,
    mime_type = excluded.mime_type,
    routing_version = excluded.routing_version,
    routing_reason = excluded.routing_reason,
    temporary_media = excluded.temporary_media,
    status = 'queued',
    attempt_count = case
      when public.page_visual_embedding_jobs.media_path = excluded.media_path
       and public.page_visual_embedding_jobs.mime_type = excluded.mime_type
      then public.page_visual_embedding_jobs.attempt_count
      else 0
    end,
    retry_after = null,
    safe_error_code = null,
    claimed_at = null,
    updated_at = now()
  returning id into queued_id;

  return jsonb_build_object(
    'queued', true,
    'jobId', queued_id,
    'temporaryMedia', is_temporary
  );
end;
$$;

